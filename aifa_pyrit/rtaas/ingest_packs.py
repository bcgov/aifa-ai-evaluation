"""Turns the attack packs and the test generator's output into New Run datasets (data/aifa_*.json).

    python -m aifa_pyrit.rtaas.ingest_packs --packs Downloads/aifa_prompt_sending.json ... --testgen tests.jsonl

Every case keeps its metadata (failure_mode, test_kind, expected_behavior, must_not_contain, checks, ...).
Each file is validated with the same loader New Run uses, so an unknown failure-mode tag fails here.
Cases that need a test hook we don't have yet (`requires`) are kept and marked `skip_reason`;
the run manager reports them as "Skipped", never as a pass.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from aifa_pyrit import datasets

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"
# hooks that exist today; anything else in `requires` makes the case Skipped
AVAILABLE_HOOKS: set[str] = set()
FILE_FOR = {"PromptSending": "aifa_prompt_sending.json", "Crescendo": "aifa_crescendo.json",
            "MultiTurn": "aifa_multiturn.json", "TAP": "aifa_tap.json"}
DEFAULT_STEP = "step2-Eligibility"


def _query(case: dict[str, Any]) -> str:
    if case.get("query") or case.get("prompt"):
        return str(case.get("query") or case.get("prompt"))
    gen = case.get("input_generator") or {}
    return str(gen.get("suffix") or case["name"])  # the long input is built at run time


def from_pack(case: dict[str, Any]) -> dict[str, Any]:
    out = {"name": case["name"], "query": _query(case), **{k: v for k, v in case.items() if k not in ("name", "query", "prompt")}}
    missing = [r for r in case.get("requires") or [] if r not in AVAILABLE_HOOKS]
    if missing:
        out["skip_reason"] = f"Needs test hook: {', '.join(missing)}"
    return out


def from_testgen(case: dict[str, Any]) -> dict[str, Any]:
    turns = case["turns"]
    out = {
        "name": f"tg_{case['id']}_{case['question_type']}",
        "query": turns[0],
        "failure_mode": case["failure_mode"],
        "attack_type": "MultiTurn" if len(turns) > 1 else "PromptSending",
        "test_kind": case["question_type"],
        "question_type": case["question_type"],
        "expected_behavior": case["expected"],
        "step": case["step"] if case["step"] != "any" else DEFAULT_STEP,
        "checks": case.get("checks") or [],
        "batch": case.get("batch"),
        "generator": case.get("generator"),
        "must_not_contain": [],
    }
    if len(turns) > 1:
        out["turns"] = turns
    if "answer" in case:
        out["gold_answer"] = case["expected"]
        out["exact_answer"] = case["answer"]
    for k in ("field", "objective", "source"):
        if k in case:
            out[k] = case[k]
    return out


def write(name: str, cases: list[dict[str, Any]], note: str) -> Path:
    path = DATA / name
    payload = {"description": note, "test_cases": cases}
    text = json.dumps(payload, indent=2, ensure_ascii=False)
    datasets._cases(text)  # same validation as New Run: names, queries, duplicates, failure-mode tags
    path.write_text(text + "\n", encoding="utf-8")
    return path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--packs", type=Path, nargs="*", default=[])
    ap.add_argument("--testgen", type=Path)
    a = ap.parse_args()

    by_type: dict[str, list[dict]] = {}
    for p in a.packs:
        for case in json.loads(p.read_text(encoding="utf-8")):
            by_type.setdefault(case["attack_type"], []).append(from_pack(case))
    for attack, cases in by_type.items():
        skipped = sum("skip_reason" in c for c in cases)
        path = write(FILE_FOR[attack], cases, f"AIFA {attack} attack pack ({len(cases)} cases, failure-mode tagged).")
        print(f"{path.name}: {len(cases)} cases, {skipped} need a test hook (Skipped)")
    if a.testgen:
        rows = [json.loads(line) for line in a.testgen.read_text(encoding="utf-8").splitlines() if line.strip()]
        cases = [from_testgen(c) for c in rows]
        path = write("aifa_testgen.json", cases, "Generated by rtaas.testgen.generate --no-llm (0 LLM tokens).")
        print(f"{path.name}: {len(cases)} cases")


if __name__ == "__main__":
    main()
